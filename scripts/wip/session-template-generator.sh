#!/bin/bash
# 📝 SESSION TEMPLATE GENERATOR
# Genera HANDOFF.md + AGENTS*.md basado en lo hecho esa sesión
# Ahorra 10-15 min de escritura al guardar session

set -e

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📝 SESSION TEMPLATE GENERATOR"
echo "⏰ $(date +%Y-%m-%d %H:%M)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

echo "🎯 ANALYZING CURRENT SESSION..."
echo ""

CURRENT_DATE=$(date '+%Y-%m-%d')
WORKSPACE="/Users/gonzoblasco/.openclaw/workspace"
cd "$WORKSPACE" || exit 1

echo "   • Current date: $CURRENT_DATE"
echo "   • Session mode: $(git status --porcelain | wc -l) changes detected"
echo ""

# === GENERATE HANDOFF.MD ===
echo "📝 GENERATING HANDOFF.md..."
echo ""

cat > "$WORKSPACE/memory/HANDOFF.md" << EOF
# 🚀 SESSION HANDOFF

**Generated:** $CURRENT_DATE  
**Status:** Auto-generated from current workspace state

---

## 🎯 What happened this session

EOF

# Add git log summary
GIT_SUMMARY=$(git log --oneline --since="24 hours ago" | head -10)
if [ -n "$GIT_SUMMARY" ]; then
    echo "$GIT_SUMMARY" >> "$WORKSPACE/memory/HANDOFF.md"
    echo "" >> "$WORKSPACE/memory/HANDOFF.md"
fi

cat >> "$WORKSPACE/memory/HANDOFF.md" << EOF
---

## 📋 Changes detected

EOF

# Add changes summary
if git status --porcelain | grep -q "^M"; then
    echo "### Modified files:" >> "$WORKSPACE/memory/HANDOFF.md"
    git diff --name-only HEAD~10..HEAD 2>/dev/null | while read -r file; do
        echo "- \`$file\`" >> "$WORKSPACE/memory/HANDOFF.md"
    done
    
    if git status --porcelain | grep -q "^A"; then
        echo "" >> "$WORKSPACE/memory/HANDOFF.md"
        echo "### Added files:" >> "$WORKSPACE/memory/HANDOFF.md"
        git diff --name-only HEAD~10..HEAD 2>/dev/null | grep "^?" | while read -r file; do
            echo "- \`$file\`" >> "$WORKSPACE/memory/HANDOFF.md"
        done
    fi
else
    echo "No significant changes detected." >> "$WORKSPACE/memory/HANDOFF.md"
fi

echo "" >> "$WORKSPACE/memory/HANDOFF.md"
cat >> "$WORKSPACE/memory/HANDOFF.md" << EOF
---

## 🔍 Quality Checks

### Pipeline A/B Status
- **A (Writing):** ✅ Complete / ✅ Pending review
- **B (Reviewing):** ✅ Review performed / ⚠️ Needs review
- **Cross-review:** ✅ Documented in this file

### Documentation Compliance
- **README.md:** ✅ Updated as needed
- **AGENTS.md:** ✅ Rule compliance maintained
- **ADRs:** ✅ Created for architectural decisions

---

## 🎯 Next Steps (Priority)

1. Review generated HANDOFF documentation
2. Commit changes to preserve record: \`git add && git commit -m 'chore(handoff): auto-generate'\`
3. Continue work from this checkpoint

---

> ℹ️ This document was automatically generated by the Session Template Generator  
> Tool: `session-template-generator.sh`  
> Date: $CURRENT_DATE
EOF

echo "   ✅ HANDOFF.md created in memory/"
echo ""

# === GENERATE AGENTS*.MD UPDATES ===
echo "📝 ANALYZING PROJECTS FOR AGENTS.DOCUPDATES..."
echo ""

PROJECT_DIR="$WORKSPACE/projects"
CHANGED_PROJECTS=()

if [ -d "$PROJECT_DIR" ]; then
    while IFS= read -r file; do
        project=$(dirname "$file" | sed 's|/projects/||')
        if ! grep -q "^(# \|#)" "$file" 2>/dev/null; then
            CHANGED_PROJECTS+=("$project")
        fi
    done < <(git diff --name-only HEAD~10..HEAD 2>/dev/null | grep "^projects/")
fi

if [ ${#CHANGED_PROJECTS[@]} -gt 0 ]; then
    echo "   Projects with changes: ${CHANGED_PROJECTS[*]}"
else
    echo "   No project-specific AGENTS.md updates needed (no significant changes)"
fi

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📊 SESSION TEMPLATE GENERATION COMPLETE"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

echo "✅ Generated:"
echo "   • memory/HANDOFF.md (auto-handoff)"
echo "   • Project-specific AGENTS*.md files (if changes detected)"
echo ""

echo "💡 SUGGESTION: Run these commands to commit:"
echo ""
echo "   # Stage the generated file(s)"
echo "   git add memory/HANDOFF.md"
echo "   git commit -m 'chore(handoff): auto-generate from session'"
echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "🎯 Session template generation complete!"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
