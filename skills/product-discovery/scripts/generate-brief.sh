#!/usr/bin/env bash
# generate-brief.sh — Generate BRIEF.md from product discovery inputs
# Usage: ./generate-brief.sh --name "<product-name>" --problem "<problem>"

set -euo pipefail

NAME=""
PROBLEM=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --name) NAME="$2"; shift 2 ;;
    --problem) PROBLEM="$2"; shift 2 ;;
    *) echo "Unknown: $1"; exit 1 ;;
  esac
done

if [[ -z "$NAME" || -z "$PROBLEM" ]]; then
  echo "Usage: $0 --name \"<name>\" --problem \"<problem>\""
  exit 1
fi

OUTPUT="BRIEF.md"

cat > "$OUTPUT" << BRIEF
# $NAME — Brief

## Problem
$PROBLEM

## Target Audience
- **Primary:**
- **Secondary:**

## Solution Concept
[Describe the proposed solution]

## Key Features
- [Feature 1]
- [Feature 2]
- [Feature 3]

## Success Metrics
- [Metric 1]
- [Metric 2]

## Assumptions
- [Assumption 1]
- [Assumption 2]

## Risks
- [Risk 1]
- [Risk 2]

## Open Questions
- [Question 1]
- [Question 2]

---

*Generated by product-discovery workflow*
BRIEF

echo "✅ Brief generated: $OUTPUT"
