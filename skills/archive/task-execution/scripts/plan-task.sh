#!/usr/bin/env bash
# plan-task.sh — Generate task plan with subtasks
# Usage: ./plan-task.sh --epic E<N> --task T<NN> --title "<title>"

set -euo pipefail

EPIC=""
TASK=""
TITLE=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --epic) EPIC="$2"; shift 2 ;;
    --task) TASK="$2"; shift 2 ;;
    --title) TITLE="$2"; shift 2 ;;
    *) echo "Unknown: $1"; exit 1 ;;
  esac
done

if [[ -z "$EPIC" || -z "$TASK" || -z "$TITLE" ]]; then
  echo "Usage: $0 --epic E<N> --task T<NN> --title \"<title>\""
  exit 1
fi

SLUG=$(echo "$TITLE" | tr '[:upper:]' '[:lower:]' | sed 's/ /-/g')
OUTPUT="${EPIC}-${TASK}-${SLUG}.md"

cat > "$OUTPUT" << PLAN
# Task: $TITLE

## Context
- **Epic:** $EPIC
- **Task:** $TASK
- **Priority:** P1
- **Complexity:** M

## Acceptance Criteria
- [ ] Criterion 1
- [ ] Criterion 2

## Plan

### Subtask 1: [Name] (~5 min)
**Verification:** [how to know it's done]
- [ ] Step 1
- [ ] Step 2

### Subtask 2: [Name] (~5 min)
**Verification:** [how to know it's done]
- [ ] Step 1
- [ ] Step 2

---

*Generated by task-execution workflow*
PLAN

echo "✅ Task plan generated: $OUTPUT"
