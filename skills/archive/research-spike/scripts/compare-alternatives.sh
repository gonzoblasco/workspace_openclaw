#!/usr/bin/env bash
# compare-alternatives.sh — Compare alternatives with weighted scoring
# Usage: ./compare-alternatives.sh --options "<A,B,C>" --criteria "<perf,maintain,learn>"

set -euo pipefail

OPTIONS=""
CRITERIA=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --options) OPTIONS="$2"; shift 2 ;;
    --criteria) CRITERIA="$2"; shift 2 ;;
    *) echo "Unknown: $1"; exit 1 ;;
  esac
done

if [[ -z "$OPTIONS" || -z "$CRITERIA" ]]; then
  echo "Usage: $0 --options \"<A,B,C>\" --criteria \"<perf,maintain,learn>\""
  exit 1
fi

OUTPUT="comparison-$(date +%Y%m%d-%H%M%S).md"

cat > "$OUTPUT" << COMPARE
# Alternatives Comparison

**Date:** $(date '+%Y-%m-%d %H:%M')

## Options
$(echo "$OPTIONS" | tr ',' '\n' | sed 's/^/- /')

## Criteria
$(echo "$CRITERIA" | tr ',' '\n' | sed 's/^/- /')

## Comparison Matrix

| Criterion | Weight | $(echo "$OPTIONS" | tr ',' ' | ') |
|-----------|--------|$(echo "$OPTIONS" | tr ',' '|' | sed 's/[^|]/-/g') |
| | | |

## Recommendation

[To be filled after evaluation]

---

*Generated by research-spike workflow*
COMPARE

echo "✅ Comparison template generated: $OUTPUT"
echo ""
echo "📋 Fill in the matrix with scores (1-10) for each option/criterion pair"
