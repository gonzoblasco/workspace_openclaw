#!/usr/bin/env bash
# postmortem.sh — Generate POSTMORTEM.md template
# Usage: ./postmortem.sh --title "<title>" --severity SEV-1|SEV-2|SEV-3|SEV-4

set -euo pipefail

TITLE=""
SEVERITY=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --title) TITLE="$2"; shift 2 ;;
    --severity) SEVERITY="$2"; shift 2 ;;
    *) echo "Unknown: $1"; exit 1 ;;
  esac
done

if [[ -z "$TITLE" || -z "$SEVERITY" ]]; then
  echo "Usage: $0 --title \"<title>\" --severity SEV-1|SEV-2|SEV-3|SEV-4"
  exit 1
fi

TIMESTAMP=$(date '+%Y-%m-%d %H:%M')
OUTPUT="POSTMORTEM-$(date +%Y%m%d-%H%M%S).md"

cat > "$OUTPUT" << POSTMORTEM
# Postmortem: $TITLE

**Date:** $TIMESTAMP
**Severity:** $SEVERITY
**Status:** Draft

