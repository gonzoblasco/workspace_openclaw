#!/usr/bin/env bash
# incident-report.sh — Generate INCIDENT_REPORT.md from incident data
# Usage: ./incident-report.sh --title "<title>" --severity SEV-1|SEV-2|SEV-3|SEV-4

set -euo pipefail

TITLE=""
SEVERITY=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --title) TITLE="$2"; shift 2 ;;
    --severity) SEVERITY="$2"; shift 2 ;;
    *) echo "Unknown: $1"; exit 1 ;;
  esac
done

if [[ -z "$TITLE" || -z "$SEVERITY" ]]; then
  echo "Usage: $0 --title \"<title>\" --severity SEV-1|SEV-2|SEV-3|SEV-4"
  exit 1
fi

TIMESTAMP=$(date '+%Y-%m-%d %H:%M')
OUTPUT="INCIDENT_REPORT-$(date +%Y%m%d-%H%M%S).md"

cat > "$OUTPUT" << REPORT
# Incident Report: $TITLE

**Date:** $TIMESTAMP
**Severity:** $SEVERITY
**Status:** Open

## Timeline

| Time | Event |
|------|-------|
| | Detection |
| | Classification |
| | Containment |
| | Resolution |

## Impact

- **Users affected:**
- **Services affected:**
- **Data loss:** No / Yes (describe)
- **Duration:**

## Containment Actions

- [ ]

## Root Cause

[To be filled after investigation]

## Resolution

[To be filled]

## Corrective Actions

| Action | Owner | Deadline | Status |
|--------|-------|----------|--------|
| | | | [ ] |

